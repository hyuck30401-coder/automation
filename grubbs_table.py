def grubbs_critical(n, alpha=0.05):
    """표본 크기 n 의 Grubbs 임계값. n < 3 이면 None (판정 불가)."""
    if n is None or n < 3:
        return None
    table = _A01 if abs(alpha - 0.01) < 1e-9 else _A05
    if n <= _N[0]:
        return table[0]
    if n >= _N[-1]:
        return table[-1]
    ln = math.log(n)
    for i in range(1, len(_N)):
        if n <= _N[i]:
            x0, x1 = math.log(_N[i - 1]), math.log(_N[i])
            y0, y1 = table[i - 1], table[i]
            return y0 + (y1 - y0) * (ln - x0) / (x1 - x0)
    return table[-1]


def max_possible_z(n, ddof=1):
    """표본 내에서 나올 수 있는 최대 |z|.

    ddof=1 이면 (n-1)/sqrt(n), ddof=0 이면 sqrt(n-1).
    임계값이 이 값보다 크면 어떤 데이터로도 flag 가 불가능하다.
    """
    if n is None or n < 2:
        return 0.0
    return (n - 1) / math.sqrt(n) if ddof == 1 else math.sqrt(n - 1)


def can_evaluate(n, alpha=0.05, ddof=1):
    """이 표본 크기에서 이상치 판정이 원리적으로 가능한가."""
    g = grubbs_critical(n, alpha)
    return g is not None and g < max_possible_z(n, ddof)
