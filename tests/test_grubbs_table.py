def _old_interp(n, table):
    if n <= _OLD_N[0]:
        return table[0]
    if n >= _OLD_N[-1]:
        return table[-1]
    ln = math.log(n)
    for i in range(1, len(_OLD_N)):
        if n <= _OLD_N[i]:
            x0, x1 = math.log(_OLD_N[i - 1]), math.log(_OLD_N[i])
            y0, y1 = table[i - 1], table[i]
            return y0 + (y1 - y0) * (ln - x0) / (x1 - x0)
    return table[-1]


FAILURES = []


def check(label, condition):
    status = "PASS" if condition else "FAIL"
    print(f"[{status}] {label}")
    if not condition:
        FAILURES.append(label)


def test_old_table_regression():
    """새 정확 계산이 옛 하드코딩 테이블(scipy 사전 계산 + 로그보간)과 1e-3 이내로 일치."""
    max_diff_05 = 0.0
    max_diff_01 = 0.0
    for n in range(3, 20001):
        got05 = grubbs_critical(n, 0.05)
        old05 = _old_interp(n, _OLD_A05)
        max_diff_05 = max(max_diff_05, abs(got05 - old05))

        got01 = grubbs_critical(n, 0.01)
        old01 = _old_interp(n, _OLD_A01)
        max_diff_01 = max(max_diff_01, abs(got01 - old01))
    check(f"alpha=0.05 전 구간(n=3..20000) 옛 테이블 대비 최대오차 {max_diff_05:.6f} < {TOLERANCE}", max_diff_05 < TOLERANCE)
    check(f"alpha=0.01 전 구간(n=3..20000) 옛 테이블 대비 최대오차 {max_diff_01:.6f} < {TOLERANCE}", max_diff_01 < TOLERANCE)


def test_known_values():
    """§S7 참조 계산기로 이미 검증한 값들과 정확히 일치하는지(소수점 6자리)."""
    cases = [
        (57, 0.05, 3.1799),
        (57, 0.01, 3.538562),
        (57, 0.025, 3.340905),
        (2910, 0.025, 4.442715),
    ]
    for n, alpha, expected in cases:
        got = grubbs_critical(n, alpha)
        check(f"grubbs_critical({n}, {alpha}) = {got:.6f} ~= {expected} (오차 {abs(got - expected):.6f})", abs(got - expected) < 5e-5)


def test_arbitrary_alpha_no_longer_aliases_005():
    """옛 버그 재현 방지: alpha=0.025 는 이제 0.05 와 달라야 한다."""
    g005 = grubbs_critical(57, 0.05)
    g0025 = grubbs_critical(57, 0.025)
    g001 = grubbs_critical(57, 0.01)
    check("alpha=0.025 임계값이 alpha=0.05 와 달라야 함 (옛 폴백 버그 재현 아님)", abs(g0025 - g005) > 0.05)
    check("alpha=0.025 임계값이 0.05 와 0.01 사이에 위치", g005 < g0025 < g001)


def test_edge_cases():
    check("n=None → None", grubbs_critical(None, 0.05) is None)
    check("n=2 (< 3) → None", grubbs_critical(2, 0.05) is None)
    check("n=3 → 유한값", math.isfinite(grubbs_critical(3, 0.05)))


